"""Shared disk-budget checks for MSsystem write paths.

The guard protects a reserve instead of checking only whether the next chunk
fits.  This matters on APFS because SQLite staging databases, WAL files and
snapshots can temporarily require several times the final file size.
"""
from __future__ import annotations

import os
import shutil
import fcntl
from contextlib import contextmanager
from pathlib import Path
from typing import Iterable

GIB = 1024 ** 3
DEFAULT_MIN_FREE_GIB = 25.0
DEFAULT_MIN_FREE_RATIO = 0.05


class InsufficientStorageError(RuntimeError):
    """Raised before a write would cross the configured disk reserve."""


@contextmanager
def exclusive_file_lock(lock_path: Path):
    """Serialize writers that must update one shared storage boundary."""
    path = Path(lock_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a+b") as handle:
        fcntl.flock(handle.fileno(), fcntl.LOCK_EX)
        try:
            yield
        finally:
            fcntl.flock(handle.fileno(), fcntl.LOCK_UN)


def _existing_anchor(path: Path) -> Path:
    candidate = Path(path).expanduser()
    while not candidate.exists() and candidate != candidate.parent:
        candidate = candidate.parent
    return candidate


def _env_float(name: str, default: float) -> float:
    try:
        return float(os.environ.get(name, default))
    except (TypeError, ValueError):
        return default


def reserve_bytes(path: Path) -> int:
    """Return the protected reserve: max(configured GiB, volume ratio)."""
    usage = shutil.disk_usage(_existing_anchor(Path(path)))
    minimum = max(0.0, _env_float("MSSYSTEM_MIN_FREE_GIB", DEFAULT_MIN_FREE_GIB))
    ratio = min(0.50, max(0.0, _env_float(
        "MSSYSTEM_MIN_FREE_RATIO", DEFAULT_MIN_FREE_RATIO
    )))
    return max(int(minimum * GIB), int(usage.total * ratio))


def storage_status(path: Path, planned_bytes: int = 0) -> dict[str, int | float | bool | str]:
    """Return volume capacity and whether ``planned_bytes`` can be written."""
    anchor = _existing_anchor(Path(path))
    usage = shutil.disk_usage(anchor)
    planned = max(0, int(planned_bytes))
    reserve = reserve_bytes(anchor)
    return {
        "path": str(Path(path).expanduser().resolve(strict=False)),
        "volume_total_bytes": usage.total,
        "volume_used_bytes": usage.used,
        "volume_free_bytes": usage.free,
        "reserve_bytes": reserve,
        "planned_bytes": planned,
        "writable_budget_bytes": max(0, usage.free - reserve),
        "ok": usage.free >= reserve + planned,
        "free_gib": round(usage.free / GIB, 2),
        "reserve_gib": round(reserve / GIB, 2),
    }


def require_storage_capacity(path: Path, planned_bytes: int = 0, operation: str = "write") -> dict:
    """Fail before a write crosses the protected disk reserve."""
    status = storage_status(path, planned_bytes)
    if not status["ok"]:
        raise InsufficientStorageError(
            f"{operation} blocked: free={status['free_gib']:.2f} GiB, "
            f"reserve={status['reserve_gib']:.2f} GiB, "
            f"planned={int(status['planned_bytes']) / GIB:.2f} GiB"
        )
    return status


def estimate_sqlite_rebuild_bytes(db_path: Path, mapping_path: Path | None = None) -> int:
    """Conservative budget for staging + validated backup + WAL/CSV overhead."""
    database_size = Path(db_path).stat().st_size if Path(db_path).exists() else 0
    mapping_size = (
        Path(mapping_path).stat().st_size
        if mapping_path is not None and Path(mapping_path).exists()
        else 0
    )
    # Existing DB stays in place while one staging DB and one consistent backup
    # are produced.  A 25% allowance covers journal/WAL and mapping growth.
    return max(2 * GIB, int(2.25 * database_size + 2 * mapping_size))


def estimate_incremental_import_bytes(
    db_paths: Iterable[Path], source_bytes: int = 0
) -> int:
    """Conservative budget for SQLite WAL growth during an incremental import."""
    databases = sum(
        path.stat().st_size for raw in db_paths
        if (path := Path(raw)).exists()
    )
    return max(2 * GIB, databases + max(0, int(source_bytes)) * 20)


def prune_generated_backups(db_path: Path, keep: int = 3) -> list[Path]:
    """Remove only superseded backups generated by the atomic DB builder."""
    database = Path(db_path)
    backups = sorted(
        database.parent.glob(f"{database.name}.prebuild_*.bak"),
        key=lambda path: (path.stat().st_mtime_ns, path.name),
        reverse=True,
    )
    removed: list[Path] = []
    for path in backups[max(0, int(keep)):]:
        path.unlink()
        removed.append(path)
        for suffix in ("-wal", "-shm"):
            Path(f"{path}{suffix}").unlink(missing_ok=True)
    return removed
